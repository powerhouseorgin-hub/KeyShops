const TEXT = { en, ta, hi, te, kn, ml };

// The invoice labels for the vehicle fields reuse the form labels (same wording as the reference receipt).
export function vehicleSaleText(lang) {
  const base = TEXT[lang] || en;
  // any key missing from a language falls back to English rather than rendering "undefined"
  return new Proxy(base, { get: (target, key) => (key in target ? target[key] : en[key]) });
}

export function fillText(template, values) {
  return String(template ?? '').replace(/\{(\w+)\}/g, (_, k) => (values[k] !== undefined ? values[k] : `{${k}}`));
}

